#[test]
fn unknown_opcodes_fall_back_to_bytes() {
    let instruction = decode(64, &[0x0f, 0x0c]);
    assert!(instruction.is_invalid());
    assert_eq!(instruction.len(), 1);
    assert_eq!(instruction.format(Syntax::Intel), ".byte 0x0f");
    assert_eq!(instruction.format(Syntax::Masm), ".byte 0x0f");
    assert_eq!(instruction.format(Syntax::Nasm), ".byte 0x0f");

    let instruction = decode(64, &[0x62, 0x00]);
    assert!(instruction.is_invalid());
    assert_eq!(instruction.len(), 1);
    assert_eq!(instruction.format(Syntax::Nasm), ".byte 0x62");
}

