/// 解码 `bytes` 的每一个前缀，要求不 panic 且游标严格前进。
fn sweep(bitness: u32, bytes: &[u8]) {
    for len in 0..=bytes.len() {
        let mut decoder = Decoder::new(bitness, &bytes[..len], 0x1_4000_1000);
        while decoder.can_decode() {
            let before = decoder.position();
            let instruction = decoder.decode();
            assert!(instruction.len() >= 1, "empty instruction for {bytes:02x?} truncated to {len}");
            assert!(decoder.position() > before, "cursor stalled for {bytes:02x?} truncated to {len}");
            assert!(decoder.position() <= len, "cursor past end for {bytes:02x?} truncated to {len}");
            let _ = instruction.format(Syntax::Masm);
        }
        assert_eq!(decoder.position(), len, "cursor did not reach end for {bytes:02x?} truncated to {len}");
    }
}

#[test]
fn truncations_decodes_or_fall_back_without_panicking() {
    for &(bitness, bytes) in FIXTURES {
        sweep(bitness, bytes);
    }
}
