#![cfg(feature = "decode")]
//! 解码器与格式化覆盖。

use data_binary_x64::decode::{Decoder, Instruction, Syntax};

/// 从 `bytes` 中精确解码一条指令。
fn decode(bitness: u32, bytes: &[u8]) -> Instruction {
    let mut decoder = Decoder::new(bitness, bytes, 0x1_4000_1000);
    decoder.decode()
}

/// 断言一种编码的 Intel 文本与长度。
fn assert_intel(bitness: u32, bytes: &[u8], text: &str, len: usize) {
    let instruction = decode(bitness, bytes);
    assert_eq!(instruction.format(Syntax::Intel), text, "intel {bytes:02x?}");
    assert_eq!(instruction.len(), len, "len {bytes:02x?}");
    assert!(!instruction.is_invalid(), "valid {bytes:02x?}");
}

#[test]
fn prologue_matches_iced_in_all_syntaxes() {
    assert_intel(64, &[0x48, 0x89, 0xe5], "mov rbp,rsp", 3);
    assert_intel(64, &[0x48, 0x83, 0xec, 0x20], "sub rsp,0x20", 4);
    assert_intel(64, &[0xc3], "ret", 1);
    assert_intel(32, &[0x55], "push ebp", 1);
    assert_intel(32, &[0x89, 0xe5], "mov ebp,esp", 2);

    let instruction = decode(64, &[0x48, 0x89, 0xe5]);
    assert_eq!(instruction.format(Syntax::Masm), "mov rbp,rsp");
    assert_eq!(instruction.format(Syntax::Nasm), "mov rbp,rsp");

    let instruction = decode(64, &[0x48, 0x83, 0xec, 0x20]);
    assert_eq!(instruction.format(Syntax::Masm), "sub rsp,0x20");
    assert_eq!(instruction.format(Syntax::Nasm), "sub rsp,0x20");
}

