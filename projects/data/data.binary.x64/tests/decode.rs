#[test]
fn decoder_cursor_tracks_position_and_ip() {
    let bytes = [0x55, 0x48, 0x89, 0xe5, 0xc3];
    let mut decoder = Decoder::new(64, &bytes, 0x1000);
    assert_eq!(decoder.position(), 0);
    assert_eq!(decoder.ip(), 0x1000);
    assert!(decoder.can_decode());

    let first = decoder.decode();
    assert_eq!(first.format(Syntax::Intel), "push rbp");
    assert_eq!(decoder.position(), 1);
    assert_eq!(decoder.ip(), 0x1001);

    decoder.decode();
    assert_eq!(decoder.position(), 4);
    let last = decoder.decode();
    assert_eq!(last.format(Syntax::Intel), "ret");
    assert_eq!(decoder.position(), 5);
    assert!(!decoder.can_decode());

    decoder.set_position(0);
    decoder.set_ip(0x2000);
    assert_eq!(decoder.ip(), 0x2000);
    assert_eq!(decoder.decode().ip(), 0x2000);
}

